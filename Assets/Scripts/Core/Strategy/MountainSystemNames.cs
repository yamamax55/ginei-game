using UnityEngine;

namespace Ginei
{
    /// <summary>
    /// 星系に与える固有名のプール（世界の名峰ベース・カタカナ・日本の名峰は除く・#星系名）。
    /// <see cref="HeritageShipNames"/>（旗艦＝世界遺産）/<see cref="MythicPlanetNames"/>（惑星＝日本神話）の星系版。
    /// 名は固定の真実の源（重複なし）。ここを差し替えれば星系の命名規則ごと変わる。
    /// 戦役生成（<c>GalaxyView</c>）はこのプールをシャッフルして重複なく引く。純データ＋純ロジック（非 MonoBehaviour・test-first）。
    /// </summary>
    public static class MountainSystemNames
    {
        /// <summary>星系名プール（世界の名峰・カタカナ・日本の山は含まない・重複なし）。</summary>
        public static readonly string[] Names =
        {
            // ヒマラヤ・カラコルム
            "エベレスト", "チョゴリ", "カンチェンジュンガ", "ローツェ", "マカルー",
            "チョオユー", "ダウラギリ", "マナスル", "アンナプルナ", "ナンガパルバット",
            "ガッシャーブルム", "ブロードピーク", "シシャパンマ", "ナムチャバルワ", "カイラス",
            "アマダブラム", "プモリ", "ティリチミール",
            // 中央アジア
            "ハンテングリ", "ポベーダ", "レーニン", "ソモニ", "ムスターグアタ", "ベルーハ",
            // ヨーロッパ・コーカサス
            "モンブラン", "マッターホルン", "アイガー", "ユングフラウ", "モンテローザ",
            "エルブルス", "カズベク", "ウシュバ", "オリンポス",
            // 南北アメリカ
            "アコンカグア", "チンボラソ", "コトパクシ", "フィッツロイ", "セロトーレ",
            "オホスデルサラド", "ローガン", "レーニア", "フッド", "ウィットニー",
            "ポポカテペトル", "オリサバ",
            // アフリカ・中東・オセアニア・南極
            "ケニア", "トゥブカル", "ダマーバンド", "アララト", "ビンソン", "コジオスコ",
        };

        /// <summary>プールの総数。</summary>
        public static int Count => Names.Length;

        /// <summary>i 番目の名（負・超過は巡回）。プール空なら空文字。</summary>
        public static string At(int i)
        {
            if (Count == 0) return "";
            int idx = ((i % Count) + Count) % Count;
            return Names[idx];
        }
    }
}
