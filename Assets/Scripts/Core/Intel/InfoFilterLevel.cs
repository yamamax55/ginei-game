namespace Ginei
{
    /// <summary>
    /// 指揮系統の情報フィルタ段階（ENDR-2 #2352）。
    /// 上位司令部が前線指揮官へ開示する情報をどれだけ絞るか＝縦方向の情報遮断の度合い。
    /// 完全開示＝そのまま伝える／部分開示＝重要点を伏せる／隠蔽＝意図的に欺く（演習偽装など）。
    /// 値が大きいほど遮断が強い（信号が落ちノイズ＝歪曲が増える）。
    /// </summary>
    public enum InfoFilterLevel
    {
        /// <summary>完全開示＝戦略状況をそのまま伝達（信号ほぼ全通）。</summary>
        完全開示 = 0,

        /// <summary>部分開示＝重要点を伏せて伝達（信号一部欠落）。</summary>
        部分開示 = 1,

        /// <summary>隠蔽＝意図的に状況を秘匿・欺瞞（信号ほぼ遮断・歪曲大）。</summary>
        隠蔽 = 2,
    }
}
