namespace Ginei
{
    /// <summary>
    /// 戦術パラダイム（ENDR-3 #2356）＝ある提督/勢力が採る戦い方の「枠組み」の状態。
    /// 既存教義に対し新機軸（フレームシフト）を仕掛けると、敵が未適応のうちは局所優位を得るが、
    /// 敵が学習して適応（対応済）すると優位は消える＝イノベーションの賞味期限を表す。
    /// </summary>
    public enum TacticalParadigm
    {
        /// <summary>正規教義＝既存の定石どおりに戦う標準状態。</summary>
        正規教義,

        /// <summary>フレームシフト済＝前提を覆す新機軸を仕掛けた状態（未対応の敵に対し優位）。</summary>
        フレームシフト済,

        /// <summary>対応済＝相手の新機軸を学習・適応し終えた状態（優位は無効化される）。</summary>
        対応済,
    }
}
